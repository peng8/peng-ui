export interface ProductSpec {
  label: string
  value: string
}

export interface Product {
  slug: string
  name: string
  /** 所属剂型 slug，对应 productCategories.slug */
  category: string
  /** 封面大图（列表卡片 + 详情页主图默认） */
  cover: string
  /** 详情页缩略图画廊（点击切换主图） */
  gallery: string[]
  /** 列表卡片上的简短一句话 */
  shortDesc: string
  /** 详情页正文描述 */
  description: string
  /** 卖点特性（勾选列表） */
  features: string[]
  /** 规格参数表（键值对） */
  specs: ProductSpec[]
  /** 起订量 */
  moq: string
  // ---- 以下为中文字段（可选，缺失则回退到英文）----
  nameZh?: string
  shortDescZh?: string
  descriptionZh?: string
  featuresZh?: string[]
  specsZh?: ProductSpec[]
}

